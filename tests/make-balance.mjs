// Turns tests/balance-report.json into js/balance.js: per-stage enemy damage and boss HP factors that
// flatten difficulty spikes and give late bosses a real fight. Rerun balance.mjs afterwards to check.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const R = JSON.parse(fs.readFileSync(path.join(root, 'tests', 'balance-report.json'), 'utf8'));
const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const median = a => { const s = [...a].sort((x, y) => x - y); return s[s.length >> 1]; };
const finals = new Set([7, 17, 27, 37, 47]);
const bossTarget = i => (i < 8 ? 8 : i < 18 ? 12 : i < 28 ? 20 : i < 38 ? 28 : 34) * (finals.has(i) ? 1.6 : 1);
const table = {};
R.forEach((r, k) => {
  const near = R.slice(Math.max(0, k - 3), k + 4).filter(x => x !== r).map(x => x.dps);
  const m = median(near);
  let dmg = 1;
  if (r.dps > m * 1.6) dmg = clamp((m * 1.3) / r.dps, 0.6, 1);           // a spike: soften it
  else if (r.i >= 18 && r.dps < m * 0.5 && r.minHp > 0.85) dmg = 1.2;     // much easier than its neighbours
  let boss = 1;
  if (r.i >= 18 && r.won) boss = clamp(bossTarget(r.i) / Math.max(3, r.bossT), 1, 3.5);
  if (r.i >= 28 && r.minHp > 0.8) dmg = Math.max(dmg, 1.15);             // late acts: enemies hit a bit harder
  if (dmg !== 1 || boss !== 1) table[r.i] = { dmg: +dmg.toFixed(2), boss: +boss.toFixed(2) };
});
const js = `'use strict';
// ---------- Balance pass (generated by tests/make-balance.mjs from a simulated run of every stage) ----------
// dmg: enemy damage multiplier for the stage · boss: boss HP multiplier. Story stages only.
const BALANCE = ${JSON.stringify(table)};
const _bal_startStage = startStage;
startStage = function (idx, kind = 'stage') {
  _bal_startStage(idx, kind);
  const b = kind === 'stage' && !CUSTOM_START && BALANCE[idx];
  if (b) W.sm = Object.assign({}, W.sm, { dmg: W.sm.dmg * b.dmg });
};
const _bal_spawnBoss = spawnBoss;
spawnBoss = function () {
  _bal_spawnBoss();
  const b = !W.custom && !W.isTower && !W.isRush && !W.isRaid && !W.isDaily && BALANCE[W.stageIdx];
  if (b && W.boss) { W.boss.hp *= b.boss; W.boss.maxHp *= b.boss; }
};
`;
fs.writeFileSync(path.join(root, 'js', 'balance.js'), js);
console.log(Object.entries(table).map(([i, t]) => `${+i + 1}: dmg ×${t.dmg} boss ×${t.boss}`).join('\n'));
